// Command workload-dataset renders a range of business days as NDJSON on stdout.
//
// It drives nothing and connects to nothing. WP-22's loader reads this stream and turns it into
// ledger rows, so that a year of the bank's own day can be bulk loaded without the model being drawn
// a second time in another language:
//
//	go -C workload run ./cmd/workload-dataset \
//	  --model ../contracts/workload/tessera-day-v1.json \
//	  --from 2025-09-01 --to 2026-08-21 --seed 42 --scale 0.0017 --customers 150000
//
// Like cmd/workload-plan it is the only part of its half of the module allowed to touch the outside
// world; internal/purity holds that boundary and names this directory as an exemption.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"os"

	"github.com/k-napiontek/tessera-bank/workload/internal/bankday"
	"github.com/k-napiontek/tessera-bank/workload/internal/dataset"
	"github.com/k-napiontek/tessera-bank/workload/internal/model"
	"github.com/k-napiontek/tessera-bank/workload/internal/seeding"
)

// This file names float64 for the scale dial and for the event estimate it prints to stderr. Neither
// is money: the one amount in the stream arrives from the engine as an int64 and is written as one.

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "workload-dataset: %v\n", err)
		os.Exit(1)
	}
}

func run() error {
	var (
		modelPath string
		from, to  string
		seed      uint64
		scale     float64
		customers int
	)
	flag.StringVar(&modelPath, "model", "", "path to a workload model (required)")
	flag.StringVar(&from, "from", "", "first business date, YYYY-MM-DD (required)")
	flag.StringVar(&to, "to", "", "last business date, inclusive, YYYY-MM-DD (required)")
	flag.Uint64Var(&seed, "seed", 42, "seed - the same seed and range give the same stream")
	flag.Float64Var(&scale, "scale", 1.0, "fraction of the model's real-time daily volume")
	flag.IntVar(&customers, "customers", 0,
		"draw from this many customers instead of the model's own population size")
	flag.Parse()

	if modelPath == "" || from == "" || to == "" {
		flag.Usage()
		return fmt.Errorf("--model, --from and --to are all required")
	}

	document, err := os.ReadFile(modelPath)
	if err != nil {
		return err
	}
	loaded, err := model.Decode(document)
	if err != nil {
		return err
	}
	first, err := bankday.ParseDate(from)
	if err != nil {
		return err
	}
	last, err := bankday.ParseDate(to)
	if err != nil {
		return err
	}

	stream, err := dataset.New(dataset.Spec{
		Model:     loaded,
		From:      first,
		To:        last,
		Seed:      seed,
		Scale:     scale,
		Customers: customers,
	})
	if err != nil {
		return err
	}

	// The currency the whole estate is opened in is WP-21's decision and stays WP-21's code. The
	// loader is told the answer rather than computing a second one, which is the same reason the
	// treasury reference is generated by the population instead of invented at either end.
	base, err := seeding.BaseCurrency(stream.People())
	if err != nil {
		return err
	}
	// The opening balance is the same kind of decision and travels the same way. F-98: without it on
	// the wire, the driver funded one figure, services/ledger-loader loaded a second and
	// mainframe/data/generate.py wrote a third, and a reconciliation between any two of them broke on
	// every account.
	opening, err := seeding.Opening(stream.People(), base)
	if err != nil {
		return err
	}
	bank := dataset.Bank{
		BaseCurrency:        string(base),
		CustomerAccountType: seeding.Liability,
		TreasuryAccountType: seeding.Asset,
		OpeningBalanceMinor: opening.Minor,
	}

	summarise(stream, loaded, scale, os.Stderr)

	out := bufio.NewWriterSize(os.Stdout, 1<<20)
	written := 0
	for line, err := range stream.Lines(bank) {
		if err != nil {
			return err
		}
		if _, err := out.Write(line); err != nil {
			return err
		}
		written++
	}
	if err := out.Flush(); err != nil {
		return err
	}
	accounts := stream.People().Size()*loaded.Population.AccountsPerCustomer + 1
	fmt.Fprintf(os.Stderr, "  Written         %d lines (1 header, %d accounts, %d actions)\n",
		written, accounts, written-accounts-1)
	return nil
}

// summarise goes to stderr so that stdout carries the stream and nothing else - the command is meant
// to be piped into a loader, and a summary on stdout would be the first row it failed to parse.
func summarise(stream dataset.Stream, loaded model.Model, scale float64, out *os.File) {
	fmt.Fprintf(out, "%s  %s  digest %s\n", loaded.ModelID, loaded.ModelVersion, loaded.Digest()[:12])
	fmt.Fprintf(out, "  Dates           %d\n", stream.Dates())
	fmt.Fprintf(out, "  Population      %d customers, %d accounts each\n",
		stream.People().Size(), loaded.Population.AccountsPerCustomer)
	fmt.Fprintf(out, "  Scale           %g of the model's %d events a day\n",
		scale, loaded.RealTime.DailyEventCount)
}
