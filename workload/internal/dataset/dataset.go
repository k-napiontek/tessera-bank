// Package dataset renders a range of business days as a stream a bulk loader can read.
//
// WP-21 executes one day against a running estate. This emits many days as data: the same model, the
// same population and the same draws, rendered as NDJSON so that services/ledger-loader can turn a
// year of them into rows without drawing the day a second time. That line is the whole reason the
// package exists - a loader that reimplemented the cohort mix, the log-normal amounts or the four
// reference formats would drift from the model the moment either side was edited, and nothing would
// notice until a run and a load disagreed about what the bank did.
//
// It performs no I/O. Lines are yielded as bytes and cmd/workload-dataset writes them, which is what
// keeps this package on the engine side of internal/purity.
package dataset

import (
	"encoding/json"
	"errors"
	"fmt"
	"hash/fnv"
	"iter"

	"github.com/k-napiontek/tessera-bank/workload/internal/arrivals"
	"github.com/k-napiontek/tessera-bank/workload/internal/bankday"
	"github.com/k-napiontek/tessera-bank/workload/internal/model"
	"github.com/k-napiontek/tessera-bank/workload/internal/population"
)

// This file names float64 for the scale dial, which is a fraction of the model's volume and not
// money. No amount is computed here: an Action carries the int64 minor units population.Draw
// produced and nothing arithmetic happens to it on the way out.

// dateStream separates one business date's draws from another's.
//
// population.Draw takes a date and uses it only to format references - the random stream is
// seed and sequence alone. For a driver running a single day that is exactly right. For a year of
// them it means every date draws the *same* customers doing the *same* things, differing only in how
// many events the day contains, and a dataset built that way would give one small cast of accounts a
// year of history and leave the rest untouched. So each date derives its own seed from the run's,
// deterministically, and the manifest records the run seed rather than any of the derived ones.
const dateStream uint64 = 0x6461_7461_7365_74_00 // "dataset"

// Kinds of line. The first line of a stream describes the population; every line after it is one
// drawn action.
const (
	KindPopulation = "population"
	KindAction     = "action"
)

// Header is the first line of a stream: what the loader needs before the first action, and what it
// could not derive from the actions themselves.
type Header struct {
	Kind                string  `json:"kind"`
	ModelID             string  `json:"modelId"`
	ModelVersion        string  `json:"modelVersion"`
	ModelDigest         string  `json:"modelDigest"`
	Seed                uint64  `json:"seed"`
	Scale               float64 `json:"scale"`
	From                string  `json:"from"`
	To                  string  `json:"to"`
	Customers           int     `json:"customers"`
	AccountsPerCustomer int     `json:"accountsPerCustomer"`

	// BaseCurrency is the one currency every account is opened in, and the reason a loader counts
	// substitutions. It is decided by seeding.BaseCurrency on the driver side rather than here,
	// because that decision is WP-21's and this package must not hold a second copy of it.
	BaseCurrency string `json:"baseCurrency"`

	// The treasury is generated by the population, one index past the last customer. Nothing in the
	// estate may invent it: it is the one account in a loaded ledger that no customer owns.
	TreasuryCustomerRef string `json:"treasuryCustomerRef"`
	TreasuryAccountRef  string `json:"treasuryAccountRef"`
}

// Action is one drawn event, on one business date.
//
// AtMillis rather than a minute: the loader stamps journal_entry.created_at from it, and that column
// is the second key a statement page orders by. A whole minute would put thousands of entries on one
// instant and leave the ordering to whatever sequence they were loaded in.
type Action struct {
	Kind        string `json:"kind"`
	Date        string `json:"date"`
	Seq         int64  `json:"seq"`
	AtMillis    int64  `json:"atMillis"`
	Cohort      string `json:"cohort"`
	Operation   string `json:"operation"`
	CustomerRef string `json:"customerRef"`
	AccountRef  string `json:"accountRef"`

	CounterpartyRef string `json:"counterpartyRef,omitempty"`
	TransferRef     string `json:"transferRef,omitempty"`
	HoldRef         string `json:"holdRef,omitempty"`
	AmountMinor     int64  `json:"amountMinor,omitempty"`
	Currency        string `json:"currency,omitempty"`
}

// Spec is what to emit. From and To are both inclusive: a range of one date is one day.
type Spec struct {
	Model     model.Model
	From, To  bankday.Date
	Seed      uint64
	Scale     float64
	Customers int // 0 keeps the model's own population size
}

var (
	// ErrRange reports a range whose last date falls before its first.
	ErrRange = errors.New("dataset: the range ends before it begins")
	// ErrCustomers reports a negative population override.
	ErrCustomers = errors.New("dataset: the customer count must not be negative")
)

// Stream is a validated spec. Everything that can fail has failed by the time one exists, which is
// what lets Lines yield bytes rather than a pair.
type Stream struct {
	people population.Population
	curve  bankday.Curve
	model  model.Model
	spec   Spec
}

// New validates a spec and resolves the model into a curve and a population.
//
// A customer count that does not divide the cohorts into whole people is refused here rather than
// rounded, because population.New refuses it: a rounded population is one the model never described,
// and every share the manifest reports would be a share of something else.
func New(spec Spec) (Stream, error) {
	if spec.To.Before(spec.From) {
		return Stream{}, fmt.Errorf("%w: %s to %s", ErrRange, spec.From, spec.To)
	}
	if spec.Customers < 0 {
		return Stream{}, fmt.Errorf("%w: %d", ErrCustomers, spec.Customers)
	}

	resolved := spec.Model
	if spec.Customers > 0 {
		resolved.Population.Size = spec.Customers
	}
	people, err := resolved.People()
	if err != nil {
		return Stream{}, err
	}
	curve, err := resolved.Curve()
	if err != nil {
		return Stream{}, err
	}
	// Built once so a bad scale is refused before the first line rather than on the first date.
	if _, err := arrivals.New(curve, spec.From, spec.Scale); err != nil {
		return Stream{}, err
	}
	return Stream{people: people, curve: curve, model: resolved, spec: spec}, nil
}

// People is the population the stream draws from.
func (s Stream) People() population.Population { return s.people }

// Dates is how many business dates the stream covers.
func (s Stream) Dates() int {
	count := 0
	for date := s.spec.From; !s.spec.To.Before(date); date = date.AddDays(1) {
		count++
	}
	return count
}

// Header builds the first line of the stream. The base currency is supplied rather than computed:
// see the field comment.
func (s Stream) Header(baseCurrency string) Header {
	treasuryCustomer, treasuryAccount := s.people.Treasury()
	return Header{
		Kind:                KindPopulation,
		ModelID:             s.model.ModelID,
		ModelVersion:        s.model.ModelVersion,
		ModelDigest:         s.model.Digest(),
		Seed:                s.spec.Seed,
		Scale:               s.spec.Scale,
		From:                s.spec.From.String(),
		To:                  s.spec.To.String(),
		Customers:           s.people.Size(),
		AccountsPerCustomer: s.model.Population.AccountsPerCustomer,
		BaseCurrency:        baseCurrency,
		TreasuryCustomerRef: treasuryCustomer,
		TreasuryAccountRef:  treasuryAccount,
	}
}

// Actions yields every drawn action in the range, date by date and in time order within a date.
//
// Lazy, for the reason arrivals.Process.Events is lazy: a year of business dates is millions of
// actions and the loader consumes them as it goes rather than holding a year in memory to write the
// first row.
func (s Stream) Actions() iter.Seq[Action] {
	return func(yield func(Action) bool) {
		for date := s.spec.From; !s.spec.To.Before(date); date = date.AddDays(1) {
			process, err := arrivals.New(s.curve, date, s.spec.Scale)
			if err != nil {
				// New proved the scale is usable and every date has demand under this curve, so
				// this is unreachable rather than tolerated. Stopping is the honest response: a
				// stream that silently skipped a date would emit a year with a hole in it.
				return
			}
			seed := seedFor(s.spec.Seed, date)
			for event := range process.Events(seed) {
				drawn := s.people.Draw(seed, event.Seq, date)
				if !yield(actionOf(drawn, date, event)) {
					return
				}
			}
		}
	}
}

// Lines yields the whole stream as NDJSON, header first.
func (s Stream) Lines(baseCurrency string) iter.Seq2[[]byte, error] {
	return func(yield func([]byte, error) bool) {
		line, err := encode(s.Header(baseCurrency))
		if !yield(line, err) || err != nil {
			return
		}
		for action := range s.Actions() {
			line, err := encode(action)
			if !yield(line, err) || err != nil {
				return
			}
		}
	}
}

func actionOf(drawn population.Action, date bankday.Date, event arrivals.Event) Action {
	action := Action{
		Kind:        KindAction,
		Date:        date.String(),
		Seq:         event.Seq,
		AtMillis:    event.At.Milliseconds(),
		Cohort:      drawn.Cohort,
		Operation:   drawn.Operation,
		CustomerRef: drawn.CustomerRef,
		AccountRef:  drawn.AccountRef,
		HoldRef:     drawn.HoldRef,
	}
	if drawn.MovesMoney() {
		action.CounterpartyRef = drawn.CounterpartyRef
		action.TransferRef = drawn.TransferRef
		action.AmountMinor = drawn.Amount.Minor
		action.Currency = string(drawn.Amount.Currency)
	}
	return action
}

// seedFor derives one business date's seed from the run's. See the dateStream comment.
func seedFor(seed uint64, date bankday.Date) uint64 {
	digest := fnv.New64a()
	// Hash never returns an error, and the interface says so.
	_, _ = digest.Write([]byte(date.String()))
	return seed ^ dateStream ^ digest.Sum64()
}

func encode(value any) ([]byte, error) {
	// Compact, one line, no HTML escaping: the references are ASCII and an escaped stream would
	// still parse while no longer being byte-identical to the one the manifest describes.
	encoded, err := json.Marshal(value)
	if err != nil {
		return nil, err
	}
	return append(encoded, '\n'), nil
}
